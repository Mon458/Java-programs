class Q4 {
    public static void main(String[] args) {
        int visitors = 0;

        System.out.println("Visitors = " + visitors);
        System.out.println("Entering = " + ++visitors);
        System.out.println("Entering = " + visitors++);
        System.out.println("After entering = " + visitors);
        System.out.println("Leaving = " + visitors--);
        System.out.println("After leaving = " + visitors);
    }
}
